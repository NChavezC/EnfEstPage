import { chromium } from "../.agenda-local/ui/node_modules/playwright/index.mjs";
import fs from "node:fs/promises";
import {fileURLToPath} from "node:url";
import assert from "node:assert/strict";
const local=new URL("../.agenda-local/",import.meta.url);
const browser=await chromium.launch({executablePath:"C:/Program Files/Google/Chrome/Application/chrome.exe",headless:true});
const context=await browser.newContext({viewport:{width:1365,height:1000},timezoneId:"Europe/London"});
await context.route("**/*",route=>["localhost","127.0.0.1"].includes(new URL(route.request().url()).hostname)?route.continue():route.abort());
const page=await context.newPage();
page.setDefaultTimeout(60000);
const errors=[];
page.on("pageerror",e=>errors.push(e.message));
let token;
try {
 await page.goto("http://localhost:5173/reservar",{waitUntil:"domcontentloaded",timeout:60000});
 await page.getByRole("button",{name:/Limpieza facial profunda/}).click();
 const d=new Date();d.setUTCDate(d.getUTCDate()+14);d.setUTCDate(d.getUTCDate()+((8-d.getUTCDay())%7));
 const day=d.toISOString().slice(0,10);
 await page.getByLabel("Fecha",{exact:true}).fill(day);
 await page.getByRole("button",{name:"12:00 – 14:00"}).click();
 await page.getByLabel("Nombre",{exact:true}).fill("Prueba");
 await page.getByLabel("Apellidos",{exact:true}).fill("Navegador");
 await page.getByLabel("Correo electrónico",{exact:true}).fill("navegador@example.invalid");
 await page.getByLabel("Teléfono",{exact:true}).fill("+56912345678");
 await page.screenshot({path:fileURLToPath(new URL("booking-desktop.png",local)),fullPage:true});
 await page.getByRole("button",{name:"Revisar cuidados y continuar"}).click();
 await page.getByRole("dialog").waitFor();
 assert.equal(await page.getByRole("button",{name:"Continuar al pago",exact:true}).isDisabled(),true);
 await page.getByLabel("He leído y acepto los cuidados previos de este tratamiento.").check();
 await page.getByRole("button",{name:"Continuar al pago",exact:true}).click();
 await page.waitForURL(/reservar\/resultado/);
 token=new URL(page.url()).searchParams.get("token");
 await page.getByRole("button",{name:"Pagar abono y confirmar"}).click();
 await page.getByRole("button",{name:"Simular pago aprobado"}).click();
 await page.getByRole("heading",{name:"Confirmada",exact:true}).waitFor();
 const booking=await context.request.get("http://localhost:5173/api/agenda/bookings/"+token).then(r=>r.json());
 assert.equal(booking.status,"confirmed");
 await fs.writeFile(new URL("browser-booking.json",local),JSON.stringify({id:booking.id,token,day}));
 await page.screenshot({path:fileURLToPath(new URL("booking-confirmed.png",local)),fullPage:true});
 await page.goto("http://localhost:5173/admin",{waitUntil:"domcontentloaded",timeout:60000});
 const password=(await fs.readFile(new URL("admin-access.txt",local),"utf8")).split("Contraseña: ")[1].trim();
 await page.getByLabel("Contraseña",{exact:true}).fill(password);
 await page.getByRole("button",{name:"Entrar",exact:true}).click();
 await page.getByRole("button",{name:"Nueva reserva",exact:true}).waitFor();
 await page.getByLabel("Fecha de agenda").fill(day);
 await page.getByRole("button",{name:/Prueba Navegador/}).waitFor();
 await page.screenshot({path:fileURLToPath(new URL("admin-desktop.png",local)),fullPage:true});
 await page.getByRole("button",{name:/Prueba Navegador/}).click();
 await page.getByRole("button",{name:"Reprogramar",exact:true}).click();
 await page.getByLabel("Hora disponible").selectOption({label:"14:10 – 16:10"});
 await page.getByRole("button",{name:"Confirmar nueva hora"}).click();
 await page.getByRole("dialog").waitFor({state:"hidden"});
 await page.getByRole("button",{name:/14:10.*Prueba Navegador/}).click();
 await page.getByRole("button",{name:"Cancelar reserva",exact:true}).click();
 await page.getByRole("dialog").waitFor({state:"hidden"});
 await page.getByRole("button",{name:"Horarios",exact:true}).click();
 await page.getByRole("heading",{name:"Horarios guardados"}).waitFor();
 await page.getByRole("button",{name:"Cargar",exact:true}).first().click();
 await page.getByLabel("Martes",{exact:true}).check();
 await page.getByRole("button",{name:"Revisar cambios",exact:true}).click();
 await page.getByText("Sin conflictos con reservas existentes. Puedes guardar el horario.").waitFor();
 await page.screenshot({path:fileURLToPath(new URL("schedule-editor.png",local)),fullPage:true});
 await page.getByRole("button",{name:"Tratamientos y cuidados",exact:true}).click();
 await page.getByRole("button",{name:/Limpieza facial profunda/}).click();
 assert.equal(await page.getByLabel("Cuidados previos",{exact:true}).inputValue(),"CUIDADOS PREVIOS");
 await page.getByRole("button",{name:"Pagos y correos",exact:true}).click();
 await page.getByRole("heading",{name:"Pagos y notificaciones"}).waitFor();
 await page.getByRole("button",{name:"Cerrar sesión",exact:true}).click();
 await page.getByRole("heading",{name:"Acceso privado"}).waitFor();
 const mobile=await context.newPage({viewport:{width:390,height:844}});
 await mobile.setViewportSize({width:390,height:844});
 await mobile.goto("http://localhost:5173/reservar",{waitUntil:"domcontentloaded",timeout:60000});
 await mobile.getByRole("button",{name:/Limpieza facial profunda/}).click();
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
 await mobile.screenshot({path:fileURLToPath(new URL("booking-mobile.png",local)),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log("PASS: reserva pública, modal obligatorio, pago simulado, confirmación, login, calendario, reprogramación, cancelación, editor por grupos, cuidados, operaciones, logout y móvil sin overflow. Zona de navegador: Londres.");
} finally {
 await browser.close();
}
